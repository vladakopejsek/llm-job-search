/**
 * The history of each application. Stage columns on `applications` say where it
 * is now; these rows say when it got there, so the tracker's stats (funnel,
 * activity per week, days to first reply) are computed from them.
 */
export const applicationEvents = pgTable(
  "application_events",
  {
    id: serial("id").primaryKey(),
    applicationId: integer("application_id")
      .notNull()
      .references(() => applications.id, { onDelete: "cascade" }),
    type: applicationEventTypeEnum("type").notNull(),
    fromStage: applicationStageEnum("from_stage"),
    toStage: applicationStageEnum("to_stage"),
    /** The day it happened (an email's date, a backdated "applied on"), not when it was recorded. */
    occurredOn: date("occurred_on").notNull(),
    /** Type-specific details: {reason}, {until}, {text, context}, {added, edited, removed}, {inferred: true}, {pausedCompany: true}, {pausedCompanies: [ids]} (a rejection). */
    payload: jsonb("payload").notNull().default(sql`'{}'::jsonb`),
    /** "queue" | "tracker" | "proposal" | "backfill" */
    source: text("source").notNull(),
    proposalId: integer("proposal_id").references(() => outcomeProposals.id),
    createdAt: createdAt(),
  },
  (t) => [index("application_events_app_idx").on(t.applicationId, t.occurredOn), index("application_events_type_idx").on(t.type, t.occurredOn)],
);

