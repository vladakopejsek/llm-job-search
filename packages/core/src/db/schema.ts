/**
 * The candidate's applications: the tracker of record. Rows come from the
 * one-time Notion import or from queue actions (Applied, Skip, Snooze).
 * Roles are matched by posting key, companies by name keys
 * (src/screen/company-key.ts) or by company_id when known.
 */
export const applications = pgTable(
  "applications",
  {
    id: serial("id").primaryKey(),
    company: text("company").notNull(),
    companyId: integer("company_id").references(() => companies.id),
    postingId: integer("posting_id").references(() => postings.id),
    stage: applicationStageEnum("stage").notNull(),
    role: text("role"),
    roleUrl: text("role_url"),
    postingKey: text("posting_key"),
    tier: text("tier"),
    appliedOn: date("applied_on"),
    lastContact: date("last_contact"),
    firstResponseOn: date("first_response_on"),
    followedUpOn: date("followed_up_on"),
    snoozedUntil: date("snoozed_until"),
    /** Why a queued role was skipped: the main feedback signal on the pipeline's picks. */
    skipReason: text("skip_reason"),
    outcome: text("outcome"),
    /** Why the company said no: the rejection email's words, or the candidate's own note. */
    rejectionReason: text("rejection_reason"),
    /** Set for rows imported from Notion; null for rows created by the queue. */
    notionUrl: text("notion_url").unique(),
    /** "queue" (decided in the queue), "outside" (applied elsewhere, logged via "Already applied") or "import" (Notion). */
    origin: text("origin").notNull().default("queue"),
    /** Where the application was sent: see CHANNELS in src/applications/constants.ts. */
    channel: text("channel"),
    /** The next call or interview (set by hand, cleared when the application closes): when, what, with whom. */
    nextStepAt: timestamp("next_step_at", { withTimezone: true }),
    /** See NEXT_STEP_KINDS in src/applications/constants.ts. */
    nextStepKind: text("next_step_kind"),
    nextStepWith: text("next_step_with"),
    /** For skip reason "applied_other_role": the application for the other role. */
    relatedApplicationId: integer("related_application_id").references((): AnyPgColumn => applications.id),
    createdAt: createdAt(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    index("applications_posting_key_idx").on(t.postingKey),
    uniqueIndex("applications_posting_idx").on(t.postingId),
    index("applications_stage_idx").on(t.stage),
  ],
);

