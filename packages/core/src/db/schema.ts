/** One agent run, of a `kind`: on the API (src/cli/daily-run.ts, Draft packs), or a skill driving the agent:* commands. */
export const agentRuns = pgTable("agent_runs", {
  id: serial("id").primaryKey(),
  startedAt: timestamp("started_at", { withTimezone: true }).notNull().defaultNow(),
  finishedAt: timestamp("finished_at", { withTimezone: true }),
  /** Code + skill version the run used, so results can be compared across changes. */
  gitSha: text("git_sha"),
  /** "evaluate" (daily-run, fresh, /daily-run, /daily-run new), "prep" (Draft packs on the API, /prep) or "replies" (/replies). */
  kind: text("kind").notNull().default("evaluate"),
  stats: jsonb("stats"),
});

/**
 * Every submission the agent made, including the ones code rejected. Evaluations
 * and prep packs are upserts that keep only the final result; this keeps the
 * history, so "how often do the checks catch the model, and what for?" can be
 * answered (src/agent/attempts.ts).
 */
export const agentAttempts = pgTable(
  "agent_attempts",
  {
    id: serial("id").primaryKey(),
    runId: integer("run_id").references(() => agentRuns.id),
    /** "evaluation", "prep" or "outcomes". */
    kind: text("kind").notNull(),
    /**
     * Null for a problem with the file as a whole (unreadable JSON, a schema error
     * outside any item). No foreign key: an id the model made up is worth recording.
     */
    postingId: integer("posting_id"),
    /** 1 for the first submission of this posting (or file) in the run, 2 for the resubmission, … */
    attempt: integer("attempt").notNull(),
    /** "stored", "stored_with_warnings", "rejected", "schema_error" or "bad_json". */
    status: text("status").notNull(),
    /** [{ code, message }], see `ProblemCode`. */
    problems: jsonb("problems").notNull().default(sql`'[]'::jsonb`),
    createdAt: createdAt(),
  },
  (t) => [index("agent_attempts_run_idx").on(t.runId, t.kind)],
);

/**
 * Every Anthropic API call (src/llm/calls.ts), from the runs, Draft packs and Ask: tokens
 * and cost, for metric 8 and the budgets. Prompts and outputs go to the trace backend,
 * when one is configured, not here.
 */
export const llmCalls = pgTable(
  "llm_calls",
  {
    id: serial("id").primaryKey(),
    runId: integer("run_id").references(() => agentRuns.id),
    /** "evaluation", "prep", "judge" or "ask" (an Ask question: no run, no posting). */
    kind: text("kind").notNull(),
    postingId: integer("posting_id").references(() => postings.id),
    /** The model that answered. */
    model: text("model").notNull(),
    /** First 12 hex characters of sha256(system prompt + output schema or tools): which prompt produced this. */
    promptVersion: text("prompt_version").notNull(),
    /** Uncached input only; the cached part is in the two columns below. */
    inputTokens: integer("input_tokens").notNull(),
    /** Includes thinking. */
    outputTokens: integer("output_tokens").notNull(),
    cacheReadTokens: integer("cache_read_tokens").notNull(),
    cacheWriteTokens: integer("cache_write_tokens").notNull(),
    webSearches: integer("web_searches").notNull().default(0),
    costUsd: doublePrecision("cost_usd").notNull(),
    latencyMs: integer("latency_ms").notNull(),
    stopReason: text("stop_reason"),
    /** Anthropic's request id, for support and for finding the call in a trace. */
    requestId: text("request_id"),
    createdAt: createdAt(),
  },
  (t) => [index("llm_calls_run_idx").on(t.runId)],
);

/**
 * What the agent read in a posting (facts, each backed by a quote that code
 * verified) and the verdict code derived from those facts. One evaluation per
 * text snapshot: resubmitting overwrites, and a changed posting gets a new one.
 */
export const evaluations = pgTable(
  "evaluations",
  {
    id: serial("id").primaryKey(),
    postingId: integer("posting_id")
      .notNull()
      .references(() => postings.id),
    snapshotId: integer("snapshot_id")
      .notNull()
      .references(() => postingSnapshots.id),
    runId: integer("run_id").references(() => agentRuns.id),
    facts: jsonb("facts").notNull(),
    verdict: verdictEnum("verdict").notNull(),
    reasons: text("reasons").array().notNull().default(sql`'{}'::text[]`),
    fitScore: integer("fit_score"),
    evidence: evidenceEnum("evidence").notNull(),
    /** Quote checks that failed, fields downgraded to unknown. */
    warnings: jsonb("warnings").notNull().default(sql`'[]'::jsonb`),
    /** "queue" (a candidate) or "audit" (a screen-rejected posting, evaluated to check the rules; queue once the screen passes it). */
    purpose: text("purpose").notNull().default("queue"),
    createdAt: createdAt(),
  },
  (t) => [
    uniqueIndex("evaluations_posting_snapshot_idx").on(t.postingId, t.snapshotId),
    index("evaluations_posting_created_idx").on(t.postingId, t.createdAt.desc()),
  ],
);

